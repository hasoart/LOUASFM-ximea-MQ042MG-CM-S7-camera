"""A deliberately small camera boundary: discover/open/configure/grab/close."""
from typing import Protocol
from ..models import CameraSettings, Frame


class Camera(Protocol):
    def discover(self) -> list[dict]: ...
    def open(self, serial: str = "") -> dict: ...
    def configure(self, settings: CameraSettings) -> tuple[CameraSettings, dict]: ...
    def start(self): ...
    def read(self, timeout_ms: int = 100) -> Frame | None: ...
    def trigger(self): ...
    def stop(self): ...
    def close(self): ...


def create_camera(backend):
    if backend == "ximea":
        from .ximea_camera import XimeaCamera
        return XimeaCamera()
    if backend == "simulated":
        from .simulated import SimulatedCamera
        return SimulatedCamera()
    raise ValueError(f"Неизвестный драйвер: {backend}")
